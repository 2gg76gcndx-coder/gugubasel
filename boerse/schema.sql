CREATE TABLE GB_FAVOURITES (
 MEMBER_ID VARCHAR2(36) NOT NULL,
 LISTING_ID VARCHAR2(36) NOT NULL,
 CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT GB_FAVOURITES_PK PRIMARY KEY (MEMBER_ID, LISTING_ID),
 CONSTRAINT GB_FAV_MEMBER_FK FOREIGN KEY (MEMBER_ID) REFERENCES GB_MEMBERS(ID),
 CONSTRAINT GB_FAV_LISTING_FK FOREIGN KEY (LISTING_ID) REFERENCES GB_LISTINGS(ID)
);
CREATE INDEX GB_FAV_LISTING_IDX ON GB_FAVOURITES(LISTING_ID);
